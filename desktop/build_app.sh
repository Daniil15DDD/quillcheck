#!/bin/sh
# Build "AI Text Checker.app" into ./dist. The bundle is only a launcher: it runs this
# project's .venv and desktop/desktop.py in place, so it works only on this Mac with the
# project at its current path. Calibration stays in the project folder; models stay in
# the Hugging Face cache. Re-run after moving the project.
set -eu
cd "$(dirname "$0")/.."
PROJECT="$(pwd)"
APP="dist/AI Text Checker.app"

[ -x .venv/bin/python ] || { echo "Missing $PROJECT/.venv" >&2; exit 1; }
.venv/bin/python -c "import webview" || { echo "pywebview is not installed in .venv" >&2; exit 1; }

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

# Icon: PNG for the running app's Dock tile, .icns for Finder.
.venv/bin/python desktop/make_icon.py desktop/icon.png
ICONSET="$(mktemp -d)/AppIcon.iconset"
mkdir -p "$ICONSET"
for s in 16 32 128 256 512; do
  sips -z $s $s desktop/icon.png --out "$ICONSET/icon_${s}x${s}.png" >/dev/null
  sips -z $((s * 2)) $((s * 2)) desktop/icon.png --out "$ICONSET/icon_${s}x${s}@2x.png" >/dev/null
done
iconutil -c icns "$ICONSET" -o "$APP/Contents/Resources/AppIcon.icns"
rm -rf "$(dirname "$ICONSET")"

cat > "$APP/Contents/MacOS/AI Text Checker" <<EOF
#!/bin/sh
# Launcher generated by desktop/build_app.sh — runs the project in place.
exec "$PROJECT/.venv/bin/python" "$PROJECT/desktop/desktop.py"
EOF
chmod +x "$APP/Contents/MacOS/AI Text Checker"

cat > "$APP/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>AI Text Checker</string>
  <key>CFBundleDisplayName</key><string>AI Text Checker</string>
  <key>CFBundleIdentifier</key><string>local.ai-text-checker.desktop</string>
  <key>CFBundleExecutable</key><string>AI Text Checker</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>LSMinimumSystemVersion</key><string>13.0</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>LSApplicationCategoryType</key><string>public.app-category.productivity</string>
</dict></plist>
EOF

codesign --force --sign - "$APP" 2>/dev/null || true  # ad-hoc signature for local use
echo "Built $PROJECT/$APP"
